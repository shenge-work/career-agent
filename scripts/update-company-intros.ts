async function main() {
  console.log('连接数据库...');
  const dbHandle = await createDatabase('./pgdata');
  const db = dbHandle.db || dbHandle;

  const users = await db.select().from(schema.users);
  const userId = users[0].id;
  console.log(`✓ 当前用户: ${users[0].email}`);

  // 获取所有公司
  const companies = await db.select().from(schema.companies)
    .where(eq(schema.companies.userId, userId));
  console.log(`公司总数: ${companies.length}`);

  let updated = 0;

  for (const [name, info] of Object.entries(COMPANY_INTROS)) {
    // 查找匹配的公司（模糊匹配）
    const company = companies.find((c: any) => c.name.includes(name) || name.includes(c.name));
    if (!company) {
      console.log(`✗ 未找到公司: ${name}`);
      continue;
    }

    // 更新 payload
    const currentPayload = (company.payload as any) || {};
    
    // 生成一句话摘要（取前80字）
    const summary = info.intro.slice(0, 80) + (info.intro.length > 80 ? '…' : '');
    
    // 构造公司简介调研条目（写入 research 数组，前端六维完整度从这里统计）
    const researchItem = {
      id: `boss-intro-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
      platform: 'BOSS直聘',
      dim: '公司简介',
      content: info.intro,
      date: new Date().toISOString().slice(0, 10),
      url: '',
    };
    
    // 合并现有 research 数组，避免重复写入
    const existingResearch = Array.isArray(currentPayload.research) ? currentPayload.research : [];
    const filteredResearch = existingResearch.filter((r: any) => r.dim !== '公司简介' || r.platform !== 'BOSS直聘');
    const newResearch = [...filteredResearch, researchItem];
    
    await db.update(schema.companies)
      .set({
        payload: {
          ...currentPayload,
          intro: info.intro,           // 完整长简介
          summary: summary,            // 一句话摘要（前端头部显示）
          industry: info.industry,    // 行业
          scale: info.size,           // 规模（前端字段名是 scale 不是 size）
          funding: info.funding,       // 融资阶段
          location: info.location,     // 地点
          research: newResearch,       // 调研条目数组（六维完整度从这里统计）
          updatedFrom: 'BOSS直聘',
        },
      })
      .where(eq(schema.companies.id, company.id));

    updated++;
    console.log(`✓ 更新: ${company.name} (${info.industry})`);
  }

  console.log(`\n完成: 更新 ${updated} 家公司的简介`);
  await dbHandle.close?.();
  process.exit(0);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
